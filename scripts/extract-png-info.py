#!/usr/bin/env python3
"""
Extract LogoGenInfo and ComfyUI workflow metadata from PNGs
generated by the comfyui-mcp-server pipeline.

Usage:
  python3 extract-png-info.py <path/to/logo_output.png>
  python3 extract-png-info.py <path> --format logo
  python3 extract-png-info.py <path> --format comfyui
  python3 extract-png-info.py <path> --format a1111
  python3 extract-png-info.py <path> --raw          # show all PNG text keys
"""

import argparse
import json
import sys
from pathlib import Path

try:
    from PIL import Image
except ImportError:
    print("ERROR: Pillow (PIL) not installed.", file=sys.stderr)
    print("Install with: pip install Pillow", file=sys.stderr)
    sys.exit(1)


def format_params_a1111(d: dict) -> str:
    """Render LogoGenInfo as A1111-style flat string."""
    parts = [
        d.get("positive_prompt", "").strip(),
    ]
    if d.get("negative_prompt"):
        parts.append(f"Negative prompt: {d['negative_prompt'].strip()}")
    parts.append(f"Steps: {d.get('steps', 'N/A')}")
    parts.append(f"Sampler: {d.get('sampler', 'N/A')}")
    parts.append(f"CFG scale: {d.get('cfg_scale', 'N/A')}")
    parts.append(f"Seed: {d.get('seed', 'N/A')}")
    parts.append(f"Size: {d.get('width', 'N/A')}x{d.get('height', 'N/A')}")
    if lora_list := d.get("loras"):
        if lora_list:
            lines = [f"{lora.get('name', '?')}: {lora.get('weight', 0.8)}" for lora in lora_list]
            parts.append("LoRAs: " + ", ".join(lines))
    return "\n".join(parts)


def extract_from_png(path: Path) -> dict:
    """Read all PNG text chunks and return structured dict."""
    if not path.exists():
        raise FileNotFoundError(f"PNG not found: {path}")

    img = Image.open(path)
    if img.format != "PNG":
        raise ValueError(f"File is not PNG: {img.format}")

    result = {"keys_found": [], "LogoGenInfo": None, "prompt": None}

    for key in img.info:
        result["keys_found"].append(key)

        if key == "LogoGenInfo":
            raw = img.info[key]
            if isinstance(raw, str):
                result["LogoGenInfo"] = json.loads(raw)
            elif isinstance(raw, bytes):
                result["LogoGenInfo"] = json.loads(raw.decode("utf-8"))

        elif key in ("prompt", "Prompt"):
            raw = img.info[key]
            if isinstance(raw, str):
                result["prompt"] = json.loads(raw)

    return result


def main():
    parser = argparse.ArgumentParser(description="Extract logo generation metadata from PNGs")
    parser.add_argument("file", help="Path to PNG output file")
    parser.add_argument(
        "--format",
        "-f",
        choices=["logo", "comfyui", "a1111", "all"],
        default="logo",
        help="Output format (default: logo)",
    )
    parser.add_argument("--raw", "-r", action="store_true", help="Include raw PNG text keys found")
    args = parser.parse_args()

    path = Path(args.file)
    try:
        data = extract_from_png(path)
    except Exception as e:
        print(f"ERROR: {e}", file=sys.stderr)
        sys.exit(1)

    if args.raw:
        print(f"--- PNG text keys: {data['keys_found']} ---\n")

    if args.format in ("logo", "all"):
        if data["LogoGenInfo"]:
            print(json.dumps(data["LogoGenInfo"], indent=2, ensure_ascii=False))
        else:
            print("# No LogoGenInfo found.")

    if args.format == "a1111":
        if data["LogoGenInfo"]:
            print(format_params_a1111(data["LogoGenInfo"]))
        else:
            print("# No LogoGenInfo found.")

    if args.format in ("comfyui", "all"):
        if data["prompt"]:
            workflow = data["prompt"]
            node_count = len(workflow) if isinstance(workflow, dict) else 0
            print(f"# ComfyUI workflow: {node_count} nodes")
            print(json.dumps(workflow, indent=2, ensure_ascii=False))
        else:
            print("# No native ComfyUI workflow prompt found.")


if __name__ == "__main__":
    main()
